import pandas as pd
import plotly.express as px
from statsmodels.tsa.holtwinters import ExponentialSmoothing

# 1. 앱 제목 및 설정
st.set_page_config(page_title="Airline L/F Predictor", layout="wide")
st.title("✈️ 노선별 L/F 미래 예측 시뮬레이터")
st.write("과거 L/F 실적 엑셀 파일을 업로드하면 미래 30일치를 예측합니다.")

# 2. 파일 업로드 기능
uploaded_file = st.file_uploader("엑셀 파일 업로드 (날짜, LF 컬럼 포함)", type=["xlsx"])

if uploaded_file:
    df = pd.read_excel(uploaded_file)
    # 데이터 전처리 (날짜 형식 변환)
    df['Date'] = pd.to_datetime(df['Date'])
    df = df.sort_values('Date')
    
    # 3. 예측 모델 (Holt-Winters 지수평활법)
    # 항공 수요의 주간 계절성(7일 단위)을 반영합니다.
    model = ExponentialSmoothing(df['LF'], seasonal='add', seasonal_periods=7).fit()
    forecast = model.forecast(30) # 향후 30일 예측
    
    # 미래 날짜 생성
    last_date = df['Date'].max()
    future_dates = pd.date_range(start=last_date + pd.Timedelta(days=1), periods=30)
    forecast_df = pd.DataFrame({'Date': future_dates, 'Predicted_LF': forecast})

    # 4. 시각화 (Plotly 그래프)
    fig = px.line(df, x='Date', y='LF', title="L/F 추이 및 미래 예측 (30일)")
    fig.add_scatter(x=forecast_df['Date'], y=forecast_df['Predicted_LF'], name="예측치", mode='lines+markers')
    st.plotly_chart(fig, use_container_width=True)

    # 5. 주요 경고
    low_lf_days = forecast_df[forecast_df['Predicted_LF'] < 40]
