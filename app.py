import streamlit as st
import pandas as pd
import plotly.express as px
from statsmodels.tsa.holtwinters import ExponentialSmoothing

st.set_page_config(page_title="Airline L/F Predictor", layout="wide")
st.title("✈️ 노선별 L/F 미래 예측 시뮬레이터 (90일 버전)")

uploaded_file = st.file_uploader("엑셀 파일을 업로드하세요 (Route, Date, LF 포함)", type=["xlsx"])

if uploaded_file:
    df = pd.read_excel(uploaded_file)
    df['Date'] = pd.to_datetime(df['Date'])
    df['LF'] = pd.to_numeric(df['LF'], errors='coerce').ffill().bfill() # 숫자 변환 및 빈칸 채우기
    
    routes = df['Route'].unique()
    selected_route = st.sidebar.selectbox("노선 선택", routes)
    route_df = df[df['Route'] == selected_route].sort_values('Date')
    
    if len(route_df) > 20:
        # 예측 기간을 90일로 설정
        forecast_days = 90 
        model = ExponentialSmoothing(route_df['LF'], seasonal='add', seasonal_periods=7).fit()
        forecast = model.forecast(forecast_days)
        
